def check(spark, engine):
    path = Path(__file__).resolve().parents[1] / "analytics/support-intent-analytics/main.py"
    spec = importlib.util.spec_from_file_location("support_intent_check_example", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    if os.environ.get("SUPPORT_INTENT_CHECK") == "longer":
        return check_real_dataset(spark, module)
    # The release uses G.711 mu-law WAVE, not the PCM used by the unit fixtures.
    payload = b"\xff" * 800
    fmt = struct.pack("<HHIIHH", 7, 1, 8000, 8000, 1, 8)
    compressed = (
        b"RIFF"
        + struct.pack("<I", 36 + len(payload))
        + b"WAVEfmt "
        + struct.pack("<I", 16)
        + fmt
        + b"data"
        + struct.pack("<I", len(payload))
        + payload
    )
    normalized, duration = module.normalize_audio(compressed)
    with wave.open(io.BytesIO(normalized)) as reader:
        assert reader.getcomptype() == "NONE" and reader.getnchannels() == 1
        assert reader.getframerate() == 16000 and reader.getnframes() == 1600
    assert duration == 0.1
    # Expected decisions are hand-written for these text fixtures, not generated by the classifier.
    cases = [
        ("a", "test", "freeze", "freeze my card", "freeze my card", "ok", "freeze", "freeze"),
        ("b", "test", "balance", "my balance", "unrecognized words", "ok", "balance", "unknown"),
        ("c", "test", "pay_bill", "pay a bill", "", "decode_error", "pay_bill", "unknown"),
        ("d", "train", "address", "change address", "change address", "ok", "address", "address"),
        ("e", "test", "abroad", "", "", "transcription_error", "unknown", "unknown"),
        ("f", "test", "balance", "my address and balance", "", "empty_transcript", "unknown", "unknown"),
        ("g", "test", "balance", "my balance", "", "missing_output", "balance", "unknown"),
    ]
    manifests, observations, expected = [], [], {}
    for request_id, split, gold, supplied, whisper, status, supplied_label, whisper_label in cases:
        manifests.append(
            (
                request_id,
                request_id,
                split,
                "synthetic-0",
                1.0,
                "decode_error" if request_id == "c" else "ok",
                "/unused/opaque.wav",
                supplied,
                gold,
            )
        )
        if status != "missing_output":
            observations.append((request_id, whisper, status))
        expected[(request_id, "supplied_asr")] = (
            supplied_label,
            "ok" if supplied.strip() else "empty_transcript",
        )
        expected[(request_id, "whisper")] = (whisper_label, status)
    outputs = module.analyze(
        spark,
        spark.createDataFrame(manifests, module.MANIFEST_SCHEMA),
        spark.createDataFrame(observations, module.OBSERVATION_SCHEMA),
    )
    second = module.analyze(
        spark,
        spark.createDataFrame(
            [
                (
                    "second",
                    "other",
                    "train",
                    "synthetic-1",
                    1.0,
                    "ok",
                    "/unused/other.wav",
                    "the app crashes",
                    "app_error",
                )
            ],
            module.MANIFEST_SCHEMA,
        ),
        spark.createDataFrame([("second", "the app crashes", "ok")], module.OBSERVATION_SCHEMA),
    )
    # Resolve the first results only after a second invocation has built different plans.
    actual = outputs["predictions"].collect()
    assert len(actual) == 2 * len(cases)
    assert {(r.request_id, r.text_source): (r.predicted_intent, r.status) for r in actual} == expected
    assert len(outputs["requests"].collect()) == len(cases)
    assert {r.selected_requests for r in second["summary"].collect()} == {1}
    assert {r.predicted_intent for r in second["topics"].collect()} == {"app_error"}
    counts = Counter((source, split) for _, split, *_ in cases for source in ("supplied_asr", "whisper"))
    topic_counts = Counter()
    confusion = Counter()
    for request_id, split, gold, *_ in cases:
        for source in ("supplied_asr", "whisper"):
            predicted, _ = expected[(request_id, source)]
            topic_counts[(source, split, "synthetic-0", predicted)] += 1
            confusion[(source, split, gold, predicted)] += 1
    assert {
        (r.text_source, r.split, r.reporting_group, r.predicted_intent): r.requests
        for r in outputs["topics"].collect()
    } == topic_counts
    assert {
        (r.text_source, r.split, r.gold_intent, r.predicted_intent): r["count"]
        for r in outputs["confusion"].collect()
    } == confusion
    for item in outputs["summary"].collect():
        subset = [case for case in cases if case[1] == item.split]
        labels = [(case[2], *expected[(case[0], item.text_source)]) for case in subset]
        correct = sum(gold == predicted for gold, predicted, _ in labels)
        unknown = sum(predicted == "unknown" for _, predicted, _ in labels)
        assert item.selected_requests == counts[(item.text_source, item.split)]
        assert item.correct_requests == correct and item.unknown_requests == unknown
        assert item.input_errors == sum(status != "ok" for _, _, status in labels)
        assert item.observed_intents == len({gold for gold, _, _ in labels})
        assert abs(item.accuracy - correct / len(labels)) < 1e-12
        assert abs(item.coverage - (len(labels) - unknown) / len(labels)) < 1e-12
        f1 = 0.0
        for intent in module.INTENTS:
            support = sum(gold == intent for gold, _, _ in labels)
            predicted = sum(label == intent for _, label, _ in labels)
            tp = sum(gold == intent and label == intent for gold, label, _ in labels)
            if support + predicted:
                f1 += 2 * tp / (support + predicted)
        assert abs(item.macro_f1_all_14 - f1 / 14) < 1e-12
    for requests, observed, message in (
        (manifests + manifests[:1], observations, "duplicate request"),
        (manifests, observations + observations[:1], "duplicate observation"),
        (manifests, observations + [("unexpected", "balance", "ok")], "unknown observation"),
        (manifests, observations + [(None, "balance", "ok")], "null observation"),
    ):
        try:
            module.analyze(
                spark,
                spark.createDataFrame(requests, module.MANIFEST_SCHEMA),
                spark.createDataFrame(observed, module.OBSERVATION_SCHEMA),
            )
        except ValueError as error:
            assert message in str(error)
        else:
            raise AssertionError(f"{message} was not rejected")
    return {"requests": len(cases), "prediction_rows": len(actual)}


def expected_real_requests(original):
    """Use connected-component traversal, rather than the example's union/find implementation."""
    labels = (
        "abroad",
        "address",
        "app_error",
        "atm_limit",
        "balance",
        "business_loan",
        "card_issues",
        "cash_deposit",
        "direct_debit",
        "freeze",
        "high_value_payment",
        "joint_account",
        "latest_transactions",
        "pay_bill",
    )
    records, links = [], {}
    for index, item in enumerate(original):
        content = item["audio"]["bytes"]
        audio_hash = hashlib.sha256(content).hexdigest()
        identifier = hashlib.sha256(f"{index}:{audio_hash}".encode()).hexdigest()
        normalized = " ".join(re.findall("[a-z0-9]+", (item["transcription"] or "").lower()))
        keys = [("audio", audio_hash)] + ([("text", normalized)] if normalized else [])
        for key in keys:
            links.setdefault(key, set()).add(index)
        # Count original mu-law frames directly, independently of the example's decoder.
        assert content[:4] == b"RIFF" and content[8:12] == b"WAVE"
        position, audio_format, data = 12, None, None
        while position + 8 <= len(content):
            name, size = struct.unpack_from("<4sI", content, position)
            chunk = content[position + 8 : position + 8 + size]
            assert len(chunk) == size
            if name == b"fmt ":
                audio_format = struct.unpack_from("<HHIIHH", chunk)
            elif name == b"data":
                data = chunk
            position += 8 + size + size % 2
        assert audio_format == (7, 1, 8000, 8000, 1, 8) and data
        seconds, valid = len(data) / 8000, True
        records.append(
            {
                "request_id": identifier,
                "seconds": seconds if valid else 0.0,
                "decode_status": "ok" if valid else "decode_error",
                "keys": keys,
                "gold_intent": labels[item["intent_class"]],
                "supplied_asr": item["transcription"] or "",
            }
        )
    remaining = set(range(len(records)))
    while remaining:
        pending, component = [min(remaining)], set()
        while pending:
            index = pending.pop()
            if index in component:
                continue
            component.add(index)
            for key in records[index]["keys"]:
                pending.extend(links[key] - component)
        group_id = min(records[index]["request_id"] for index in component)
        for index in component:
            records[index]["duplicate_group"] = group_id
            records[index]["split"] = "train" if int(group_id[:8], 16) % 5 < 2 else "test"
        remaining -= component
    selected, duration = [], 0.0
    for item in sorted(records, key=lambda item: item["request_id"]):
        if len(selected) == 96 or duration + item["seconds"] > 600:
            break
        selected.append(item)
        duration += item["seconds"]
    return {item["request_id"]: item for item in selected}, duration, labels


def check_real_dataset(spark, module):
    """Retain observed metrics without treating a structural pass as a quality threshold."""
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download

    source = Path(
        hf_hub_download(
            "PolyAI/minds14",
            "en-US/train-00000-of-00001.parquet",
            repo_type="dataset",
            revision="28a8ee8911625fe71b2e0462c3dc14132d1058fa",
            token=False,
        )
    )
    assert hashlib.sha256(source.read_bytes()).hexdigest() == (
        "37004471dc896ce20771b3fdda0ee8fb33ec7a030fb4e2fd047c561ec0a1ee30"
    )
    original = pq.read_table(source, columns=["audio", "transcription", "intent_class"]).to_pylist()
    assert len(original) == 563
    expected, duration, labels = expected_real_requests(original)
    outputs = module.run(spark, max_clips=96, max_seconds=600)
    actual_requests = [row.asDict() for row in outputs["requests"].collect()]
    actual_predictions = [row.asDict() for row in outputs["predictions"].collect()]
    assert len(actual_requests) == len(expected) and len(actual_predictions) == 2 * len(expected)
    assert {item["request_id"] for item in actual_requests} == set(expected)
    for item in actual_requests:
        reference = expected[item["request_id"]]
        for key in ("duplicate_group", "split", "gold_intent", "supplied_asr", "decode_status", "seconds"):
            assert item[key] == reference[key], (item["request_id"], key)
        assert re.fullmatch("[a-f0-9]{64}", item["request_id"])
    assert len(actual_requests) <= 96 and sum(item["seconds"] for item in actual_requests) <= 600
    pairs = {(item["request_id"], item["text_source"]) for item in actual_predictions}
    assert pairs == {
        (identifier, source) for identifier in expected for source in ("supplied_asr", "whisper")
    }
    for item in actual_predictions:
        reference = expected[item["request_id"]]
        assert item["gold_intent"] == reference["gold_intent"] and item["split"] == reference["split"]
        assert item["predicted_intent"] in {*labels, "unknown"}
        if item["text_source"] == "supplied_asr":
            assert item["text"] == reference["supplied_asr"]
            assert item["status"] == ("ok" if reference["supplied_asr"].strip() else "empty_transcript")
        else:
            assert item["status"] in {"ok", "empty_transcript", "decode_error", "transcription_error"}
            if reference["decode_status"] != "ok":
                assert item["status"] == "decode_error"
        if item["status"] == "ok":
            assert item["text"].strip()
        else:
            assert item["predicted_intent"] == "unknown"
    # The pinned qualification corpus has known-valid audio. Error-retention
    # fixtures above separately check failed inputs without accepting a regression here.
    valid_audio_ids = {identifier for identifier, item in expected.items() if item["decode_status"] == "ok"}
    successful_whisper_ids = {
        item["request_id"]
        for item in actual_predictions
        if item["text_source"] == "whisper" and item["status"] == "ok" and item["text"].strip()
    }
    assert valid_audio_ids
    assert successful_whisper_ids == valid_audio_ids, {
        "missing_success": sorted(valid_audio_ids - successful_whisper_ids),
        "unexpected_success": sorted(successful_whisper_ids - valid_audio_ids),
    }
    summary = [row.asDict() for row in outputs["summary"].collect()]
    assert {(row["text_source"], row["split"]) for row in summary} == {
        (row["text_source"], row["split"]) for row in actual_predictions
    }
    for item in summary:
        subset = [
            row
            for row in actual_predictions
            if row["text_source"] == item["text_source"] and row["split"] == item["split"]
        ]
        correct = sum(row["gold_intent"] == row["predicted_intent"] for row in subset)
        unknown = sum(row["predicted_intent"] == "unknown" for row in subset)
        assert item["selected_requests"] == len(subset)
        assert item["correct_requests"] == correct and item["unknown_requests"] == unknown
        assert item["input_errors"] == sum(row["status"] != "ok" for row in subset)
        assert item["observed_intents"] == len({row["gold_intent"] for row in subset})
        assert abs(item["accuracy"] - correct / len(subset)) < 1e-12
        assert abs(item["coverage"] - (len(subset) - unknown) / len(subset)) < 1e-12
        f1 = 0.0
        for intent in labels:
            support = sum(row["gold_intent"] == intent for row in subset)
            predicted = sum(row["predicted_intent"] == intent for row in subset)
            tp = sum(row["gold_intent"] == row["predicted_intent"] == intent for row in subset)
            if support + predicted:
                f1 += 2 * tp / (support + predicted)
        assert abs(item["macro_f1_all_14"] - f1 / 14) < 1e-12
    assert {
        (row.text_source, row.split, row.reporting_group, row.predicted_intent): row.requests
        for row in outputs["topics"].collect()
    } == Counter(
        (row["text_source"], row["split"], row["reporting_group"], row["predicted_intent"])
        for row in actual_predictions
    )
    assert {
        (row.text_source, row.split, row.gold_intent, row.predicted_intent): row["count"]
        for row in outputs["confusion"].collect()
    } == Counter(
        (row["text_source"], row["split"], row["gold_intent"], row["predicted_intent"])
        for row in actual_predictions
    )
    return {
        "max_clips": 96,
        "max_seconds": 600,
        "selected_requests": len(expected),
        "selected_seconds": duration,
        "summary": summary,
        "class_support": [
            {"split": split, "intent": label, "requests": count}
            for (split, label), count in sorted(
                Counter((row["split"], row["gold_intent"]) for row in actual_requests).items()
            )
        ],
        "predictions": actual_predictions,
    }
