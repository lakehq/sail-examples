"""Generate agent context from the checked facts and the example catalog.

Public outputs (repository root), built from public facts only:
- llms.txt          things to remember when using Sail, then the example catalog
- agent-context.md  a compact block to paste into a project's AGENTS.md or CLAUDE.md

    uv run tools/build_context.py            # write the files
    uv run tools/build_context.py --check    # fail if the files are out of date

A variant can be built from more fact directories into another directory, and
can also be rendered as an agent skill (`--skill-out <dir>/SKILL.md`). Facts
loaded with `--private-facts-dir`, or marked `"private": True`, are listed in
their own section, and are refused unless every output is inside `--private-root`.
"""

import argparse
import json
import os
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tests"))

from catalog import LEVELS, ROOT, discover_examples, discover_facts

CATEGORY_TITLES = {
    "run-and-connect": "Run and connect",
    "configure": "Configure",
    "python-udfs": "Python UDFs",
    "data-sources": "Data sources",
    "missing-features": "Not available",
    "silent-behavior": "Behaves differently from Spark",
    "ai-functions": "AI and vector functions",
}
PRIVATE_TITLE = "Known issues"
SIZE_BUDGET = 8 * 1024  # bytes; agent-context.md is meant to be loaded into every agent session
SKILL_SIZE_BUDGET = (
    24 * 1024
)  # bytes (about 6k tokens); a skill loads only when relevant, so it carries every fact

SKILL_DESCRIPTION = (
    "Use when writing, running, debugging or reviewing Spark SQL or DataFrame code that runs on Sail "
    "(pysail), including local data engineering with Sail on CSV, Parquet, JSON or Delta Lake files. "
    "Checked facts about where Sail differs from Apache Spark: starting and connecting, SAIL_* "
    "configuration, catalogs, Python UDFs, loading files, missing features, AI and vector functions."
)


def checked_against() -> str:
    engines = tomllib.loads((ROOT / "tests" / "engines.toml").read_text())
    pins = {re.split(r"[=<>\[]", dep)[0]: dep for dep in engines["sail"]["deps"]}
    return f"{pins['pysail']} with {pins['pyspark-client']}"


def one_line(fact) -> str:
    return " ".join(fact.meta["text"].split())


def ordered(facts):
    return sorted(facts, key=lambda f: (f.meta.get("order", 100), f.id))


def sections(facts) -> list[tuple[str, list[str]]]:
    """Public facts grouped by category, then private facts in their own section."""
    public = [f for f in facts if not f.meta.get("private")]
    grouped = []
    for category, title in CATEGORY_TITLES.items():
        texts = [one_line(f) for f in ordered(f for f in public if f.meta["category"] == category)]
        if texts:
            grouped.append((title, texts))
    private = [one_line(f) for f in ordered(f for f in facts if f.meta.get("private"))]
    if private:
        grouped.append((PRIVATE_TITLE, private))
    return grouped


def context_body(facts, *, core_only: bool = False) -> list[str]:
    lines = [
        "Sail runs most Spark SQL and DataFrame code unchanged over Spark Connect. Write ordinary Spark",
        "code; the points below are where Sail needs specific knowledge. Each point is backed by an",
        f"automated check against {checked_against()}; details attributed to the Sail docs or marked",
        "as measured separately are not covered by that check.",
    ]
    shown = [f for f in facts if f.meta.get("core") or f.meta.get("private")] if core_only else facts
    for title, texts in sections(shown):
        lines += ["", f"## {title}", ""]
        lines += [f"- {text}" for text in texts]
    if core_only and len(shown) < len(facts):
        lines += ["", f"{len(facts) - len(shown)} more checked facts are in llms.txt."]
    lines += [
        "",
        "Docs: https://docs.lakesail.com/sail/latest/",
        "Check Spark code for unsupported features: https://migrate.lakesail.com/",
    ]
    return lines


def render_agent_context(facts) -> str:
    # The paste-able file carries the core facts only, so it stays small enough to load every session.
    return "\n".join(["# Using Sail (agent context)", "", *context_body(facts, core_only=True)]) + "\n"


def render_skill(facts, examples, examples_base: Path) -> str:
    lines = [
        "---",
        "name: sail",
        f"description: {json.dumps(SKILL_DESCRIPTION)}",  # quoted: the text contains ": "
        "---",
        "",
        "<!-- Generated by tools/build_context.py from checked facts. Do not edit by hand. -->",
        "",
        "# Sail: checked facts for writing Spark code on Sail",
        "",
        *context_body(facts),
        "",
        "## Runnable examples",
        "",
        "Each example runs unchanged on Apache Spark and on Sail and is checked to return the same result.",
        "Copy the pattern: a `run(spark)` function plus an in-process `SparkConnectServer` entry point.",
        "Each path's README says when to use the example and how it works.",
        "",
    ]
    for example in examples:
        path = examples_base / example.path.relative_to(ROOT)
        lines.append(f"- {example.meta['title']}: {path}")
    return "\n".join(lines) + "\n"


def render_llms_txt(facts, examples) -> str:
    lines = [
        "# Sail examples",
        "",
        "> Runnable examples of Spark SQL and DataFrame code on Sail, an engine that runs Spark code over",
        "> Spark Connect. Every example that uses only Spark APIs is checked to return the same result on",
        "> Apache Spark and on Sail, except the Iceberg example, which is checked against an independent",
        "> reference.",
        "",
        f"Things to remember when using Sail (checked against {checked_against()}):",
        "",
    ]
    for _, texts in sections(facts):
        lines += [f"- {text}" for text in texts]
    lines += ["", "## Examples", ""]
    for example in examples:
        rel = example.path.parent.relative_to(ROOT)
        lines.append(f"- [{example.meta['title']}]({rel}/README.md): {example.meta['description']}")
    lines += [
        "",
        "## Optional",
        "",
        "- [Agent context to paste into AGENTS.md](agent-context.md)",
        "- [Sail documentation](https://docs.lakesail.com/sail/latest/)",
        "- [Check Spark code for unsupported features](https://migrate.lakesail.com/)",
    ]
    return "\n".join(lines) + "\n"


GALLERY_START = "<!-- gallery:start (generated by tools/build_context.py from each README's front matter) -->"
GALLERY_END = "<!-- gallery:end -->"
GALLERY_GROUPS = {
    "Start here": ("quickstart",),
    "Analytics": ("analytics",),
    "Data pipelines": ("pipelines",),
    "AI data preparation": ("ai", "multimodal"),
    "Python integration and testing": ("python", "migrate"),
    "Agent workflows": ("agents",),
}


def render_gallery(examples) -> str:
    """The README's example tables, grouped by task, with each example's level."""
    lines = [GALLERY_START]
    for heading, tiers in GALLERY_GROUPS.items():
        chosen = sorted(
            (e for e in examples if e.meta["tier"] in tiers),
            key=lambda e: LEVELS.index(e.meta["level"]),
        )
        if not chosen:
            continue
        lines += [
            "",
            f"### {heading}",
            "",
            "| Example | What you will do |",
            "|---|---|",
        ]
        for example in chosen:
            rel = example.path.parent.relative_to(ROOT)
            use = example.meta.get("summary", example.meta["description"].removeprefix("Use when "))
            level = example.meta["level"]
            lines.append(f"| [{example.meta['title']}]({rel}/README.md) ({level}) | {use} |")
    lines += ["", GALLERY_END]
    return "\n".join(lines)


def render_readme(current: str, examples) -> str:
    """README.md with its generated gallery replaced; everything outside the markers is kept."""
    start, end = current.index(GALLERY_START), current.index(GALLERY_END) + len(GALLERY_END)
    return current[:start] + render_gallery(examples) + current[end:]


def inside(path: Path, root: Path) -> bool:
    """True if `path` is `root` or below it, comparing real files (safe on case-insensitive disks)."""
    real = path.resolve()
    return any(a.exists() and os.path.samefile(a, root) for a in (real, *real.parents))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the outputs are out of date")
    parser.add_argument("--facts-dir", type=Path, action="append", help="fact directories (default: facts/)")
    parser.add_argument(
        "--private-facts-dir",
        type=Path,
        action="append",
        default=[],
        help="directories whose facts are all treated as private",
    )
    parser.add_argument(
        "--private-root", type=Path, help="the only directory private facts may be written into"
    )
    parser.add_argument("--out-dir", type=Path, default=ROOT)
    parser.add_argument("--skill-out", type=Path, help="also render an agent skill to this SKILL.md path")
    parser.add_argument(
        "--examples-base",
        type=Path,
        default=ROOT,
        help="directory the skill names as the examples' location (default: this checkout)",
    )
    args = parser.parse_args()

    facts = [f for d in (args.facts_dir or [ROOT / "facts"]) for f in discover_facts(d)]
    for directory in args.private_facts_dir:
        for fact in discover_facts(directory):
            fact.meta["private"] = True
            facts.append(fact)
    examples = discover_examples()
    outputs = {
        args.out_dir / "agent-context.md": render_agent_context(facts),
        args.out_dir / "llms.txt": render_llms_txt(facts, examples),
    }
    if args.skill_out:
        outputs[args.skill_out] = render_skill(facts, examples, args.examples_base)
    readme = ROOT / "README.md"
    if args.out_dir.resolve() == ROOT.resolve() and GALLERY_START in readme.read_text():
        outputs[readme] = render_readme(readme.read_text(), examples)

    has_private = any(f.meta.get("private") for f in facts)
    if has_private:
        root = args.private_root
        outside = [p for p in outputs if root is None or not root.exists() or not inside(p, root)]
        if outside:
            print(f"refusing to write private facts outside --private-root ({root}): {outside}")
            return 2

    status = 0
    for path, text in outputs.items():
        size = len(text.encode())
        # The public agent-context.md is meant for always-loaded files, so it keeps the tight budget.
        # A build with private facts is loaded on demand (as a skill), so all its outputs get the skill budget.
        context_budget = SKILL_SIZE_BUDGET if has_private else SIZE_BUDGET
        budget = {"agent-context.md": context_budget, "SKILL.md": SKILL_SIZE_BUDGET}.get(path.name)
        if budget and size > budget:
            print(f"{path} is {size} bytes, over the {budget}-byte budget")
            status = 1
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{path} is out of date")
                status = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return status


if __name__ == "__main__":
    sys.exit(main())
